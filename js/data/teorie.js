// Tahák k první písemce, sestavený ze zápisků z cvičení (prpa.hs) a cheat sheetu.
// Bloky kódu:
//   kind 'expr' – jeden výraz na řádek, za `--` je výsledek z GHCi (ověřeno testem)
//   kind 'defs' – definice, které jde načíst do konzole; `try` = výrazy k vyzkoušení
